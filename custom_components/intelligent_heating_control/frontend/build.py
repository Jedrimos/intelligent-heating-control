#!/usr/bin/env python3
"""
Build script: Concatenates frontend/src/*.js files into frontend/ihc-panel.js

The source files are split as follows:
  00_constants.js   – Top-level constants (DOMAIN, MODE_LABELS, etc.)
  01_styles.css.js  – STYLES template literal (complete CSS)
  09_main.js        – IHCPanel class shell: constructor, lifecycle, _renderTabContent.
                      Contains a marker "=== METHODS_INSERTED_HERE ===" where
                      method files 02–08 are injected by this build script.
  02_utils.js       – Data helpers, _callService, _toast, entity pickers, etc.
  03_tab_dashboard.js – _renderOverview() and Dashboard tab logic
  04_tab_rooms.js   – _renderRooms(), _renderRoomDetail(), schedule/calendar inline
  05_tab_settings.js  – _renderSettings() and all settings sections
  06_tab_diagnose.js  – _renderDiagnose()
  07_tab_curve.js   – _renderCurve(), _collectCurvePoints(), _drawCurve()
  08_modals.js      – _showAddRoomModal(), _showEditRoomModal(), modal helpers

Usage:
    cd custom_components/intelligent_heating_control
    python3 frontend/build.py

Run this after editing any file in frontend/src/ to regenerate ihc-panel.js.
The generated ihc-panel.js is the file loaded by Home Assistant.
"""
import os

SRC_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src")
OUTPUT  = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ihc-panel.js")

# Files that are injected between Part A and Part B of 09_main.js
# (raw method fragments that live inside the IHCPanel class body)
METHOD_FILES = [
    "02_utils.js",
    "03_tab_dashboard.js",
    "04_tab_rooms.js",
    "06_tab_diagnose.js",
    "05_tab_settings.js",
    "07_tab_curve.js",
    "08_modals.js",
]

MARKER = "// === METHODS_INSERTED_HERE ==="


def read_file(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def build_i18n_js():
    """Turn frontend/i18n/en.py into JS constants (IHC_I18N_EN / _PATTERNS / _WORDS)."""
    import importlib.util, json, re
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "i18n", "en.py")
    spec = importlib.util.spec_from_file_location("ihc_i18n_en", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    norm = lambda t: re.sub(r"\s+", " ", t).strip()
    exact = {norm(k): v for k, v in mod.EXACT.items()}
    out = [
        "// ── GENERATED from frontend/i18n/en.py by build.py – edit en.py, not this ──",
        "const IHC_I18N_EN = " + json.dumps(exact, ensure_ascii=False, indent=0, sort_keys=True) + ";",
        # A broken pattern must never take the whole panel down - compile defensively.
        "const IHC_I18N_EN_PATTERNS = " + json.dumps([[p, r] for p, r in mod.PATTERNS], ensure_ascii=False)
        + ".map(([p, r]) => { try { return [new RegExp(p, \"u\"), r]; } catch (e) { console.warn(\"IHC i18n pattern\", p, e); return null; } }).filter(Boolean);",
        "const IHC_I18N_EN_WORDS = " + json.dumps(sorted(mod.WORDS, key=lambda w: -len(w[0])), ensure_ascii=False) + ";",
    ]
    # v2.6 – further languages (frontend/i18n/languages.py); missing texts fall back to English
    lpath = os.path.join(os.path.dirname(os.path.abspath(__file__)), "i18n", "languages.py")
    lspec = importlib.util.spec_from_file_location("ihc_i18n_languages", lpath)
    lmod = importlib.util.module_from_spec(lspec)
    lspec.loader.exec_module(lmod)
    langs = {}
    for i, code in enumerate(lmod.LANGS):
        langs[code] = {norm(k): v[i] for k, v in lmod.T.items()}
    out.append("const IHC_I18N_LANGS = " + json.dumps(langs, ensure_ascii=False, sort_keys=True) + ";")
    out.append(
        "const IHC_I18N_LANG_PATTERNS = Object.fromEntries(Object.entries("
        + json.dumps({c: [[p, r] for p, r in lmod.PATTERNS.get(c, [])] for c in lmod.LANGS}, ensure_ascii=False)
        + ").map(([c, list]) => [c, list.map(([p, r]) => { try { return [new RegExp(p, \"u\"), r]; } catch (e) { return null; } }).filter(Boolean)]));"
    )
    out.append("")
    return "\n".join(out)


def build_card_langs():
    """v2.6 – write per-language phrase tables into the two Lovelace cards (between markers)."""
    import importlib.util, json, re
    base = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location("ihc_i18n_languages", os.path.join(base, "i18n", "languages.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    src = {**mod.T, **mod.CARD}
    for fname in ("ihc-room-card.js", "ihc-dashboard-card.js"):
        path = os.path.join(base, fname)
        text = read_file(path)
        table_name = "_IHC_CARD_EN" if "room" in fname else "_IHC_DB_EN"
        m = re.search(r"const " + table_name + r" = (\[.*?\n\]);", text, re.S)
        keys = re.findall(r'\["((?:[^"\\]|\\.)*)", "', m.group(1))
        langs = {c: {k: src[k][i] for k in keys if k in src} for i, c in enumerate(mod.LANGS)}
        block = ("// <IHC_CARD_LANGS> generated by build.py from i18n/languages.py\n"
                 "const _IHC_CARD_LANGS = " + json.dumps(langs, ensure_ascii=False, sort_keys=True) + ";\n"
                 "// </IHC_CARD_LANGS>")
        text = re.sub(r"// <IHC_CARD_LANGS>.*?// </IHC_CARD_LANGS>", lambda _: block, text, flags=re.S)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)


def build():
    build_card_langs()
    # 1. Global constants + styles (must come before class definition)
    preamble_files = ["00_constants.js", "01_styles.css.js"]
    parts = []
    # v2.6 – English UI dictionary generated from frontend/i18n/en.py (single source)
    parts.append(build_i18n_js())

    for fname in preamble_files:
        fpath = os.path.join(SRC_DIR, fname)
        if not os.path.exists(fpath):
            print(f"ERROR: Missing {fname}")
            return
        parts.append(f"// === {fname} ===\n")
        parts.append(read_file(fpath))
        parts.append("\n")

    # 2. 09_main.js is split at the MARKER – method files are injected between the two halves
    main_path = os.path.join(SRC_DIR, "09_main.js")
    if not os.path.exists(main_path):
        print("ERROR: Missing 09_main.js")
        return

    main_content = read_file(main_path)
    if MARKER not in main_content:
        print(f"ERROR: Marker '{MARKER}' not found in 09_main.js")
        return

    part_a, part_b = main_content.split(MARKER, 1)
    # Strip the "// (methods from ...)" placeholder comment line from part_b
    part_b_lines = part_b.splitlines(keepends=True)
    # Skip the first line(s) that are just the placeholder comment
    skip = 0
    for line in part_b_lines:
        stripped = line.strip()
        if stripped.startswith("//") or stripped == "":
            skip += 1
        else:
            break
    part_b_clean = "".join(part_b_lines[skip:])

    parts.append("// === 09_main.js (Part A: class open + lifecycle) ===\n")
    parts.append(part_a)

    # 3. Inject method files inside the class body
    for fname in METHOD_FILES:
        fpath = os.path.join(SRC_DIR, fname)
        if not os.path.exists(fpath):
            print(f"WARNING: Missing method file {fname} – skipping")
            continue
        parts.append(f"\n// === {fname} ===\n")
        parts.append(read_file(fpath))
        parts.append("\n")

    # 4. Append Part B of 09_main.js (class closing brace + registration)
    parts.append("\n// === 09_main.js (Part B: class close + registration) ===\n")
    parts.append(part_b_clean)

    combined = "".join(parts)

    with open(OUTPUT, "w", encoding="utf-8") as fh:
        fh.write(combined)

    print(f"Built {OUTPUT}")
    print(f"  {len(combined)} chars, {combined.count(chr(10))} lines")
    print(f"  Source files: {len(preamble_files) + 1 + len(METHOD_FILES)}")


if __name__ == "__main__":
    build()
